"""Generate Task 15 governance and request-budget evidence."""

import json
import os
import sys
import tempfile
from pathlib import Path
from typing import Any, Dict, List

os.environ.setdefault("CREWAI_DISABLE_TELEMETRY", "true")
os.environ.setdefault("CREWAI_DISABLE_TRACKING", "true")
os.environ.setdefault("OTEL_SDK_DISABLED", "true")
os.environ.setdefault("HF_HUB_OFFLINE", "1")
os.environ.setdefault("TRANSFORMERS_OFFLINE", "1")

PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from crewai.hooks.tool_hooks import ToolCallHookContext, run_before_tool_call_hooks
from fastapi.testclient import TestClient

from src.cred_agent.agents.lookup_agent import CredLoanApplicationLookupTool
from src.cred_agent.api import create_app
from src.cred_agent.services.tool_permissions import (
    LOOKUP_AGENT_ROLE,
    LOOKUP_TOOL_NAME,
    RETRIEVAL_AGENT_ROLE,
)

TRANSCRIPT_PATH = PROJECT_ROOT / "evaluation" / "task15_governance_transcript.md"
RISK_DOCUMENT = PROJECT_ROOT / "docs" / "governance-and-risk.md"


def _request(
    client: TestClient,
    query: str,
    session_id: str,
) -> Dict[str, Any]:
    response = client.post(
        "/ask",
        json={"query": query, "session_id": session_id},
    )
    if response.status_code != 200:
        raise RuntimeError(f"Demo request failed with HTTP {response.status_code}.")
    return response.json()


def _response_section(title: str, query: str, body: Dict[str, Any]) -> List[str]:
    return [
        f"## {title}",
        "",
        f"- Query: {query}",
        f"- Response type: `{body['structured_response']['response_type']}`",
        f"- Workflow invoked: `{body['workflow_invoked']}`",
        f"- Budget outcome: `{body['budget_outcome']}`",
        f"- Estimated input tokens: {body['estimated_input_tokens']}",
        f"- Estimated request tokens: {body['estimated_total_tokens']}",
        f"- Synthetic estimated cost: {body['synthetic_estimated_cost']}",
        f"- Answer: {body['response_text']}",
        "",
    ]


def run_demo() -> str:
    original_budget_environment = {
        name: os.environ.get(name)
        for name in (
            "CRED_REQUEST_MAX_INPUT_TOKENS",
            "CRED_REQUEST_MAX_TOTAL_TOKENS",
            "CRED_REQUEST_MAX_ESTIMATED_COST",
        )
    }
    transcript: List[str] = [
        "# Task 15 Governance and Runtime Budget Demonstration",
        "",
        "Generated by `python scripts\\run_task15_governance_demo.py` using the "
        "existing FastAPI endpoints, real CrewAI agent workflow, and real "
        "two-turn AutoGen review. All models are deterministic local MOCK_LLM "
        "adapters; no external LLM API or key is used.",
        "",
        "The estimator counts one token per four UTF-8 bytes, rounded up. "
        "Synthetic cost is illustrative only, not an actual API charge.",
        "",
    ]
    with tempfile.TemporaryDirectory(prefix="cred-task15-") as temporary_directory:
        app = create_app(
            log_path=Path(temporary_directory) / "task15_api.jsonl"
        )
        try:
            with TestClient(app) as client:
                kb_query = "How is EMI calculated?"
                kb = _request(client, kb_query, "task15-kb")
                if kb["budget_outcome"] != "within_budget":
                    raise AssertionError("Normal KB request did not fit its budget.")
                transcript.extend(_response_section("Normal knowledge-base request", kb_query, kb))

                lookup_query = "What is the status of loan application APP-1001?"
                lookup = _request(client, lookup_query, "task15-lookup")
                if lookup["budget_outcome"] != "within_budget":
                    raise AssertionError("Normal lookup request did not fit its budget.")
                transcript.extend(
                    _response_section("Normal authorized loan lookup", lookup_query, lookup)
                )

                combined_query = (
                    "What is the status of APP-1001 and how is EMI calculated?"
                )
                combined = _request(client, combined_query, "task15-combined")
                if (
                    combined["budget_outcome"] != "within_budget"
                    or combined["structured_response"]["response_type"] != "combined"
                ):
                    raise AssertionError("Combined-intent query was not preserved.")
                transcript.extend(
                    _response_section("Combined-intent request", combined_query, combined)
                )

                os.environ["CRED_REQUEST_MAX_INPUT_TOKENS"] = "8"
                oversized_query = "oversized-" + ("x" * 100)
                oversized = _request(client, oversized_query, "task15-oversized")
                if (
                    oversized["budget_outcome"] != "input_limit_exceeded"
                    or oversized["workflow_invoked"]
                    or oversized["history_messages"] != 0
                ):
                    raise AssertionError("Oversized input was not rejected early.")
                transcript.extend(
                    [
                        "## Oversized input rejected before workflow execution",
                        "",
                        "- The configured input cap was temporarily set to 8 estimated tokens.",
                        f"- Estimated input tokens: {oversized['estimated_input_tokens']}",
                        f"- Safe response type: `{oversized['structured_response']['response_type']}`",
                        f"- Workflow invoked: `{oversized['workflow_invoked']}`",
                        f"- Session history messages: {oversized['history_messages']}",
                        "",
                    ]
                )

                os.environ["CRED_REQUEST_MAX_INPUT_TOKENS"] = "512"
                os.environ["CRED_REQUEST_MAX_TOTAL_TOKENS"] = "8192"
                os.environ["CRED_REQUEST_MAX_ESTIMATED_COST"] = "1"
                cumulative = _request(
                    client,
                    combined_query,
                    "task15-cumulative",
                )
                if (
                    cumulative["budget_outcome"] == "within_budget"
                    or cumulative["structured_response"]["response_type"] != "safe_error"
                    or cumulative["history_messages"] != 0
                ):
                    raise AssertionError(
                        "Cumulative CrewAI/AutoGen budget was not enforced safely."
                    )
                transcript.extend(
                    [
                        "## Cumulative workflow budget rejected safely",
                        "",
                        "- The combined request ran the CrewAI specialist/composer work, "
                        "then the two-turn AutoGen stage was conservatively preflighted "
                        "against the remaining per-request budget.",
                        f"- Budget outcome: `{cumulative['budget_outcome']}`",
                        f"- Estimated request tokens: {cumulative['estimated_total_tokens']} "
                        "(limit: 8192)",
                        f"- Final response type: `{cumulative['structured_response']['response_type']}`",
                        f"- Workflow had started: `{cumulative['workflow_invoked']}`",
                        f"- Incomplete session history messages: {cumulative['history_messages']}",
                        "",
                    ]
                )
        finally:
            for name, value in original_budget_environment.items():
                if value is None:
                    os.environ.pop(name, None)
                else:
                    os.environ[name] = value

    lookup_tool = CredLoanApplicationLookupTool()
    unauthorized_context = ToolCallHookContext(
        tool_name=LOOKUP_TOOL_NAME,
        tool_input={"record_id": "APP-1001"},
        tool=lookup_tool,
        agent=type("AgentIdentity", (), {"role": RETRIEVAL_AGENT_ROLE})(),
    )
    unauthorized_blocked = run_before_tool_call_hooks(unauthorized_context)
    if not unauthorized_blocked:
        raise AssertionError("Unauthorized retrieval-agent lookup was not blocked.")
    authorized_context = ToolCallHookContext(
        tool_name=LOOKUP_TOOL_NAME,
        tool_input={"record_id": "APP-1001"},
        tool=lookup_tool,
        agent=type("AgentIdentity", (), {"role": LOOKUP_AGENT_ROLE})(),
    )
    if run_before_tool_call_hooks(authorized_context):
        raise AssertionError("Lookup Agent was incorrectly denied.")
    authorized_result = json.loads(lookup_tool.run(record_id="APP-1001"))
    transcript.extend(
        [
            "## Least-autonomy dispatch checks",
            "",
            f"- Retrieval Agent lookup attempt blocked before service execution: "
            f"`{unauthorized_blocked}`",
            "- Lookup Agent authorized dispatch: `True`",
            f"- Authorized tool result: application `{authorized_result['record_id']}`, "
            f"status `{authorized_result['status']}`",
            "- Response Composer has no tools; AutoGen Reviewer and Editor have no tools.",
            "",
            "Only the Lookup Agent receives the status tool. The actual CrewAI "
            "pre-dispatch hook checks the caller role and exact `record_id` payload; "
            "MOCK_LLM also refuses unauthorized tool names or alternate argument "
            "schemas before emitting a tool call. Combined intent still selects both "
            "authorized specialists.",
            "",
            "## Risk classification and mitigations",
            "",
            "- Classification: **HIGH**.",
            "- Financial domain; loan status and amounts; fraud-review flags and "
            "escalation recommendations; possible PAN/Aadhaar/bank identifiers; "
            "risks from fabricated terms, prompt injection, or unauthorized tool use.",
            "- Implemented: synthetic data, deterministic offline MOCK_LLM, PII masking, "
            "input injection guardrails, groundedness checks, Pydantic validation, "
            "AutoGen Reviewer/Editor, privacy-safe JSONL logs, agent-specific tool "
            "permissions, and request-scoped budgets.",
            f"- Full justification and residual limitations: `{RISK_DOCUMENT.relative_to(PROJECT_ROOT)}`.",
            "- This project does not claim production readiness, regulatory compliance, "
            "or certification.",
            "",
        ]
    )
    result = "\n".join(transcript)
    TRANSCRIPT_PATH.parent.mkdir(parents=True, exist_ok=True)
    TRANSCRIPT_PATH.write_text(result, encoding="utf-8")
    return result


if __name__ == "__main__":
    print(run_demo())
