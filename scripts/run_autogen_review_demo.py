"""Demonstrate the two-agent AutoGen review using the local project workflow."""

import os
import sys
from pathlib import Path
from typing import Dict, List

os.environ["CREWAI_DISABLE_TELEMETRY"] = "true"
os.environ["CREWAI_DISABLE_TRACKING"] = "true"
os.environ["OTEL_SDK_DISABLED"] = "true"
os.environ["HF_HUB_OFFLINE"] = "1"
os.environ["TRANSFORMERS_OFFLINE"] = "1"

PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from src.cred_agent.crew import run_customer_query
from src.cred_agent.services.autogen_review import (
    AutoGenReviewResult,
    review_response,
)

TRANSCRIPT_PATH = PROJECT_ROOT / "evaluation" / "autogen_review_transcript.md"
INJECTED_CLAIM = "Every loan application is guaranteed approval."


def _format_case(
    title: str,
    question: str,
    draft: str,
    result: AutoGenReviewResult,
    evidence_sources: List[str],
) -> List[str]:
    verdict = result.verdict
    response = result.response
    lines = [
        f"## {title}",
        "",
        f"- User question: {question}",
        f"- Evidence source IDs: {', '.join(evidence_sources) or 'none'}",
        f"- Draft: {draft}",
        f"- Approved: `{verdict.approved}`",
        f"- Final answer: {response.response}",
        f"- Reason: {verdict.reason}",
        f"- AutoGen turns: {result.turn_count} "
        f"({', '.join(result.agent_order)})",
        f"- Structured verdict validated: `{result.structured_message_received}`",
        "",
    ]
    return lines


def run_demo() -> str:
    kb_query = "What are the eligibility criteria for a personal loan?"
    kb_result = run_customer_query(kb_query)
    kb_review = review_response(
        kb_query,
        kb_result.structured_response,
    )

    loan_query = "What is the status of loan application APP-1001?"
    loan_result = run_customer_query(loan_query)
    loan_review = review_response(
        loan_query,
        loan_result.structured_response,
    )

    injected_draft = (
        kb_result.structured_response.response
        + " "
        + INJECTED_CLAIM
    )
    revised_review = review_response(
        kb_query,
        kb_result.structured_response,
        draft_answer=injected_draft,
    )
    unsupported_review = review_response(
        kb_query,
        kb_result.structured_response,
        draft_answer=INJECTED_CLAIM,
    )

    if not kb_review.verdict.approved or kb_review.response.response != (
        kb_result.structured_response.response
    ):
        raise AssertionError("Grounded knowledge-base draft was not preserved.")
    if not loan_review.verdict.approved or loan_review.response.response != (
        loan_result.structured_response.response
    ):
        raise AssertionError("Grounded loan lookup draft was not preserved.")
    if INJECTED_CLAIM in revised_review.response.response:
        raise AssertionError("Unsupported injected claim remained in the answer.")
    if unsupported_review.response.response != (
        "I don't have sufficient information in the available knowledge base "
        "to answer this question."
    ):
        raise AssertionError("Unsupported-only draft did not produce safe fallback.")
    if any(
        result.turn_count != 2
        or result.agent_order != ["Reviewer", "Editor"]
        or not result.structured_message_received
        for result in (kb_review, loan_review, revised_review, unsupported_review)
    ):
        raise AssertionError("AutoGen did not complete two structured agent turns.")

    cases: Dict[str, tuple[str, str, AutoGenReviewResult, List[str]]] = {
        "Grounded knowledge-base draft": (
            kb_query,
            kb_result.structured_response.response,
            kb_review,
            kb_result.structured_response.source_documents,
        ),
        "Grounded loan lookup draft": (
            loan_query,
            loan_result.structured_response.response,
            loan_review,
            loan_result.structured_response.source_documents,
        ),
        "Injected unsupported claim removed": (
            kb_query,
            injected_draft,
            revised_review,
            kb_result.structured_response.source_documents,
        ),
        "Only unsupported claim falls back safely": (
            kb_query,
            INJECTED_CLAIM,
            unsupported_review,
            kb_result.structured_response.source_documents,
        ),
    }

    lines = [
        "# AutoGen Reviewer and Editor Demonstration",
        "",
        "This transcript is generated by `python scripts\\run_autogen_review_demo.py`.",
        "The CrewAI workflow and the AutoGen Reviewer/Editor both use deterministic "
        "local mock clients. No external LLM APIs or network services are used.",
        "",
        "The AutoGen team is a `RoundRobinGroupChat` with exactly two agent turns: "
        "`Reviewer` then `Editor`. The Editor emits a Pydantic `ReviewVerdict` "
        "registered as `StructuredMessage[ReviewVerdict]`. Both agents have no tools.",
        "",
        "The Reviewer receives the guarded original question, CrewAI draft, retrieved "
        "context, and validated lookup observation where applicable. Editing is "
        "checked again by the existing groundedness validator.",
        "",
    ]
    for title, (question, draft, result, sources) in cases.items():
        lines.extend(
            _format_case(title, question, draft, result, sources)
        )
    transcript = "\n".join(lines)
    TRANSCRIPT_PATH.parent.mkdir(parents=True, exist_ok=True)
    TRANSCRIPT_PATH.write_text(transcript, encoding="utf-8")
    return transcript


if __name__ == "__main__":
    print(run_demo())
